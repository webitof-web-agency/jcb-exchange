const normalize = (message: string) => message
  .toLocaleLowerCase('en-IN')
  .replace(/purchse/gu, 'purchase')
  .replace(/purchaes/gu, 'purchases')
  .replace(/cash[-\s]?flow/gu, 'cash flow')
  .replace(/approv(?:al|els?)/gu, 'approval')
  .replace(/\s+/gu, ' ')
  .trim();

const pageKeySet = new Set<string>(SCOPED_FINANCE_PAGE_KEYS);

export const financePageKeyFor = (message: string, context: FinancePageContext = {}): ScopedFinancePageKey | null => {
  if (context.moduleKey && pageKeySet.has(context.moduleKey)) return context.moduleKey as ScopedFinancePageKey;
  const normalized = normalize(message);
  if (!normalized) return null;
  // CRM has its own read-only tools; Finance page aliases must not capture CRM import/history questions.
  if (/\bcrm\b/u.test(normalized)) return null;
  if (normalized.includes('account ledger masters')) return 'account-ledger-masters';
  if (normalized.includes('import opening balances')) return 'import-opening-balances';
  for (const [key, aliases] of PAGE_ALIASES) {
    if (aliases.some((alias) => normalized.includes(alias))) return key;
  }
  return null;
};

