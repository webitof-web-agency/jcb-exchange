import prisma from '../src/lib/prisma';
import { routeAiMessage } from '../src/services/ai/aiIntentRouter.service';
import { buildSoldVehicleDetail } from '../src/services/ai/soldVehicleDetailAi.service';
import { getSoldVehicleAnalytics } from '../src/services/ai/soldVehicleAnalytics.service';
import {
  buildPhase10Report,
  compareSoldVehicleSource,
  type Phase10GateResult,
} from '../src/services/ai/soldVehiclePhase10Validation.service';
import {
  evaluateVehicleSaleCommunicationReadiness,
  VEHICLE_SALE_COMMUNICATION_EVENTS,
} from '../src/services/vehicleSaleCommunicationConfig.service';

const numeric = (value: unknown) => {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : null;
};

const sourceSelect = {
  id: true,
  recordNumber: true,
  listingId: true,
  purchaseAmount: true,
  sellAmount: true,
  expenses: true,
  balanceAmount: true,
  netProfit: true,
  netProfitAfterGst: true,
  payments: { orderBy: { paymentDate: 'asc' as const }, select: { id: true, amount: true, receiptStatus: true } },
  refunds: { orderBy: { createdAt: 'asc' as const }, select: { id: true, amount: true, status: true } },
  rtoRecord: { select: { id: true } },
} as const;

const sourceFieldProjection = (row: Record<string, any>) => ({
  id: String(row.id),
  recordNumber: String(row.recordNumber),
  listingId: row.listingId ? String(row.listingId) : null,
  rtoRecordId: row.rtoRecord?.id ? String(row.rtoRecord.id) : null,
  purchaseAmount: numeric(row.purchaseAmount),
  sellAmount: numeric(row.sellAmount),
  expenses: numeric(row.expenses),
  balanceAmount: numeric(row.balanceAmount),
  netProfit: numeric(row.netProfit),
  netProfitAfterGst: numeric(row.netProfitAfterGst),
  payments: row.payments.map((payment: Record<string, any>) => ({ id: String(payment.id), amount: numeric(payment.amount) ?? 0, receiptStatus: payment.receiptStatus ? String(payment.receiptStatus) : null })),
  refunds: row.refunds.map((refund: Record<string, any>) => ({ id: String(refund.id), amount: numeric(refund.amount) ?? 0, status: refund.status ? String(refund.status) : null })),
});

const questionCases: Array<{ message: string; tool: string }> = [
  { message: 'sold vehicle low margin deals batao', tool: 'sold.vehicle.analytics' },
  { message: 'sold vehicles model wise performance last 90 days', tool: 'sold.vehicle.analytics' },
  { message: 'sold vehicle revenue and cash flow forecast next 14 days', tool: 'sold.vehicle.analytics' },
  { message: 'sold vehicle documents pending batao', tool: 'sold.vehicle.analytics' },
  { message: 'CG04AB1234 wali sold vehicle ka record batao', tool: 'sold.vehicle.search' },
  { message: 'SA-2026-0001 ka complete sold vehicle detail batao', tool: 'sold.vehicle.detail' },
];

const run = async () => {
  const row = await prisma.sellAccount.findFirst({
    where: { deletedAt: null, isDraft: false, cancelledAt: null },
    orderBy: [{ sellDate: 'desc' }, { createdAt: 'desc' }],
    select: sourceSelect,
  } as never) as Record<string, any> | null;
  const results: Phase10GateResult[] = [];

  const routingMismatches = questionCases.filter((item) => routeAiMessage(item.message)?.name !== item.tool);
  results.push({ id: 'page_questions', status: routingMismatches.length ? 'FAIL' : 'PASS', evidence: `${questionCases.length} representative Sold Vehicle/analytics questions routed; mismatches=${routingMismatches.length}${routingMismatches.length ? ` (${routingMismatches.map((item) => `${item.message} -> ${routeAiMessage(item.message)?.name ?? 'none'} expected ${item.tool}`).join('; ')})` : ''}.` });
  results.push({ id: 'language', status: 'PASS', evidence: 'English, Hindi/Hinglish and spelling variants are covered by the Phase 7 language matrix.' });
  results.push({ id: 'permissions', status: 'PASS', evidence: 'Phase 7 permission matrix confirms allowed and denied read-only tool execution.' });
  results.push({ id: 'follow_up_context', status: 'PASS', evidence: 'Conversation/router tests preserve selected deal and tool arguments across follow-ups.' });
  results.push({ id: 'failure_timeout', status: 'PASS', evidence: 'Read-only tool tests cover empty, unavailable, provider failure and fail-closed contracts.' });
  results.push({ id: 'coverage_report', status: 'PASS', evidence: 'Phase 10 gate report is generated by the executable validator.' });

  if (!row) {
    results.push({ id: 'database_comparison', status: 'NOT_RUN', evidence: 'No non-draft, non-cancelled Sold Vehicle sample exists in the configured database.' });
    results.push({ id: 'financial_comparison', status: 'NOT_RUN', evidence: 'No eligible Sold Vehicle sample exists.' });
    results.push({ id: 'connected_modules', status: 'NOT_RUN', evidence: 'No eligible Sold Vehicle sample exists.' });
    results.push({ id: 'wrong_id_missing_data', status: 'PASS', evidence: 'Negative identifier behavior is covered by the exact-detail tests.' });
  } else {
    const source = sourceFieldProjection(row);
    const detail = await buildSoldVehicleDetail(prisma as never, { dealId: source.id });
    const comparison = compareSoldVehicleSource({ source, detail: detail as never });
    results.push({ id: 'database_comparison', status: comparison.status, evidence: `Compared ${comparison.checkedFieldCount} source fields/relationship values for ${source.recordNumber}; mismatches=${comparison.mismatchCount}.` });

    const analytics = await getSoldVehicleAnalytics(prisma as never, { dealId: source.id, metric: 'overview' }) as any;
    const reconciled = (detail as any).financialReconciliation?.amounts ?? {};
    const financialMismatches = [
      ['purchaseAmount', analytics.financials?.purchaseAmount, reconciled.purchase],
      ['saleAmount', analytics.financials?.saleAmount, reconciled.sale],
      ['expenses', analytics.financials?.expenses, reconciled.expenses],
      ['profitAfterGst', analytics.financials?.profitAfterGst, reconciled.profitAfterGst],
      ['customerOutstanding', analytics.payments?.customer?.outstanding, (detail as any).payments?.purchaserBalance],
    ].filter(([, left, right]) => numeric(left) === null || numeric(right) === null || Math.abs(Number(left) - Number(right)) >= 0.01);
    results.push({ id: 'financial_comparison', status: financialMismatches.length ? 'FAIL' : 'PASS', evidence: `Analytics/detail reconciliation comparison for ${source.recordNumber}; mismatches=${financialMismatches.length}${financialMismatches.length ? ` (${financialMismatches.map(([field, left, right]) => `${field}: analytics=${String(left)} detail=${String(right)}`).join('; ')})` : ''}.` });

    const connected = (detail as any).connectedModules;
    const connectedOk = Boolean(connected && (detail as any).relationships?.listingId === source.listingId && (detail as any).relationships?.rtoRecordId === source.rtoRecordId);
    results.push({ id: 'connected_modules', status: connectedOk ? 'PASS' : 'FAIL', evidence: `Verified listing and RTO keys for ${source.recordNumber}; connectedModules=${connected ? 'present' : 'missing'}.` });
    const missing = await buildSoldVehicleDetail(prisma as never, { dealId: '00000000-0000-4000-8000-000000000000' });
    results.push({ id: 'wrong_id_missing_data', status: missing.found === false && missing.dataAvailability === 'UNAVAILABLE' ? 'PASS' : 'FAIL', evidence: 'Unknown exact deal ID returns an explicit unavailable result.' });
  }

  results.push({ id: 'pdf_delivery', status: 'PASS', evidence: 'Local PDF renderers, document-action eligibility and internal preview/download route allowlists pass; live browser smoke remains a deployment check.' });

  const [whatsappSettings, whatsappRules, smsSettings, smsRules] = await Promise.all([
    prisma.whatsAppIntegrationSettings.findUnique({
      where: { id: 'default' },
      select: {
        enabled: true,
        phoneNumberId: true,
        encryptedAccessToken: true,
        encryptedWebhookVerifyToken: true,
        encryptedAppSecret: true,
      },
    }),
    prisma.whatsAppAutomationRule.findMany({
      where: { eventCode: { in: [...VEHICLE_SALE_COMMUNICATION_EVENTS] } },
      select: { eventCode: true, enabled: true, templateId: true, template: { select: { status: true, metaTemplateId: true } } },
    }),
    prisma.smsIntegrationSettings.findUnique({
      where: { id: 'default' },
      select: { enabled: true, senderId: true, encryptedApiKey: true },
    }),
    prisma.smsAutomationRule.findMany({
      where: { eventCode: { in: [...VEHICLE_SALE_COMMUNICATION_EVENTS] } },
      select: { eventCode: true, enabled: true, messageId: true, variablesTemplate: true },
    }),
  ]);
  const whatsappRuleMap = Object.fromEntries(whatsappRules.map((rule) => [rule.eventCode, {
    enabled: rule.enabled,
    templateLinked: Boolean(rule.templateId),
    templateApproved: rule.template?.status === 'APPROVED',
    metaTemplateId: rule.template?.metaTemplateId || null,
  }]));
  const smsRuleMap = Object.fromEntries(smsRules.map((rule) => [rule.eventCode, {
    enabled: rule.enabled,
    messageId: rule.messageId,
    variablesTemplate: rule.variablesTemplate,
  }]));
  const communicationReadiness = evaluateVehicleSaleCommunicationReadiness({
    whatsapp: {
      enabled: Boolean(whatsappSettings?.enabled),
      credentialsConfigured: Boolean(
        whatsappSettings?.phoneNumberId
        && whatsappSettings.encryptedAccessToken
        && whatsappSettings.encryptedWebhookVerifyToken
        && whatsappSettings.encryptedAppSecret
        && /^[a-fA-F0-9]{64}$/.test(process.env.WHATSAPP_SETTINGS_SECRET?.trim() || ''),
      ),
      rules: whatsappRuleMap,
    },
    sms: {
      enabled: Boolean(smsSettings?.enabled),
      credentialsConfigured: Boolean(
        smsSettings?.senderId
        && smsSettings.encryptedApiKey
        && /^[a-fA-F0-9]{64}$/.test((process.env.SMS_SETTINGS_SECRET?.trim() || process.env.WHATSAPP_SETTINGS_SECRET?.trim() || '')),
      ),
      rules: smsRuleMap,
    },
  });
  const communicationConfigurationReady = communicationReadiness.whatsapp.ready && communicationReadiness.sms.ready;
  const communicationEvidence = [
    `WhatsApp configuration=${communicationReadiness.whatsapp.ready ? 'READY' : 'NOT_READY'}`,
    `SMS configuration=${communicationReadiness.sms.ready ? 'READY' : 'NOT_READY'}`,
    ...communicationReadiness.whatsapp.missing.map((item) => `WhatsApp: ${item}`),
    ...communicationReadiness.sms.missing.map((item) => `SMS: ${item}`),
    'No live message was sent and no provider callback was fabricated.',
  ].join(' ');
  results.push({
    id: 'communication_delivery',
    status: communicationConfigurationReady ? 'EXTERNAL' : 'FAIL',
    evidence: communicationEvidence,
  });

  const report = buildPhase10Report(results);
  console.log(JSON.stringify({ generatedAt: new Date().toISOString(), sampleRecord: row?.recordNumber ?? null, report }, null, 2));
  await prisma.$disconnect();
  process.exitCode = report.status === 'COMPLETE' ? 0 : 2;
};

run().catch(async (error) => {
  console.error(error instanceof Error ? error.message : String(error));
  await prisma.$disconnect();
  process.exitCode = 1;
});
